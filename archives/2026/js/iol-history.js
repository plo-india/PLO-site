function renderTeamHeader(team, addSpacing = false) {
    const spacingClass = addSpacing ? " pt-3 border-top" : "";
    return `<li class="list-group-item badge-text${spacingClass}">
                                <div class="IndiaIconTextBadge">
                                    <span>${team.name}</span><span><img src="icons/india.png" alt="TeamIndia"/></span>
                                </div>
                            </li>`;
}

function renderTeamLeader(team) {
    const leaderLabel = team.leaders ? "Team Leaders" : "Team Leader";
    const leaderNames = team.leaders ? team.leaders.join(" &amp; ") : team.leader;
    return `<li class="list-group-item">
                                <small class="text-muted">${leaderLabel}: ${leaderNames}</small>
                            </li>`;
}

function renderMember(member) {
    if (!member.medal) {
        return `<li class="list-group-item">${member.name}</li>`;
    }
    const m = MEDAL_CONFIG[member.medal];
    return `<li class="list-group-item">${member.name}
                                <span data-bs-toggle="tooltip" data-bs-placement="right" data-bs-title="${m.label}" class="iconOnly"><img src="${m.src}" alt="${m.label}"/></span>
                                <div class="IconTextBadge ${m.cls}"><span>${m.label}</span><span><img src="${m.badgeSrc}" alt="${m.label}"/></span></div>
                            </li>`;
}

function renderCampMember(person) {
    if (!person.awards || person.awards.length === 0) {
        return `<li class="list-group-item">${person.name}</li>`;
    }
    let iconOnlySpans = '';
    let badgeDivs = '';
    for (const award of person.awards) {
        const cfg = MEDAL_CONFIG[award];
        const placement = award === 'hm' ? 'bottom' : 'right';
        iconOnlySpans += `<span data-bs-toggle="tooltip" data-bs-placement="${placement}" data-bs-title="${cfg.label}" class="iconOnly"><img src="${cfg.src}" alt="${cfg.label}"/></span>`;
        badgeDivs += `<div class="IconTextBadge ${cfg.cls}"><span>${cfg.label}</span><span><img src="${cfg.badgeSrc}" alt="${cfg.label}"/></span></div>`;
    }
    return `<li class="list-group-item">${person.name}
                                    ${iconOnlySpans}
                                    ${badgeDivs}
                                </li>`;
}

function renderIOLSections() {
    for (const [year, data] of Object.entries(IOL_DATA)) {
        const ul = document.getElementById("IOL_names_" + year);
        if (!ul) continue;
        const teams = [...data.teams].sort((a, b) => {
            if (a.name === "India Saffron") return -1;
            if (b.name === "India Saffron") return 1;
            return 0;
        });
        let html = "";
        for (let i = 0; i < teams.length; i++) {
            html += renderTeamHeader(teams[i], i > 0);
            for (const member of teams[i].members) {
                html += renderMember(member);
            }
            html += renderTeamLeader(teams[i]);
        }
        ul.innerHTML = html;
    }
}

function renderCampSections() {
    for (const [year, members] of Object.entries(CAMP_DATA)) {
        const ul = document.getElementById("camp_names_" + year);
        if (!ul) continue;
        ul.innerHTML = members.map(renderCampMember).join("\n");
    }
}

document.addEventListener("DOMContentLoaded", function () {
    renderIOLSections();
    renderCampSections();
    document.querySelectorAll('[data-bs-toggle="tooltip"]').forEach(el => new bootstrap.Tooltip(el));
});
