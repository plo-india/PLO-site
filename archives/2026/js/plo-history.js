const PLO_META_FIELDS = [
    ["problemCommittee",   "Problem Committee"   ],
    ["nationalCoordinator","National Coordinator"],
    ["juryChair",          "Jury Chair"          ],
    ["sponsors",           "Sponsors"            ]
];

function renderPLOSection(year, data) {
    let metaHtml = "";
    if (data.meta) {
        for (const [key, label] of PLO_META_FIELDS) {
            if (data.meta[key]) {
                metaHtml += `<p><span>${label}:</span> ${data.meta[key]}</p>\n                            `;
            }
        }
    }

    let cardsHtml = "";
    if (data.problems && data.problems.length > 0) {
        const cols = data.problems.map(p => {
            const authorLine = p.author
                ? `<p class="card-text"><span>Authors name:</span> ${p.author}</p>\n                                        `
                : "";
            return `<div class="col h-100">
                                <div class="card">
                                    <div class="card-body">
                                        <h5 class="card-title">${p.title}</h5>
                                        <h6 class="card-subtitle mb-2 text-body-secondary"><span>Marks:</span> ${p.marks}</h6>
                                        ${authorLine}<a href="resources.html" class="card-link text-decoration-none">Download</a>
                                    </div>
                                </div>
                            </div>`;
        }).join("\n                            ");
        cardsHtml = `\n                        <div class="row row-cols-1 row-cols-md-3 g-4">
                            ${cols}
                        </div>`;
    }

    return `<ul class="list-group list-group-flush">
                            <h1 class="plo-header">Panini Linguistics Olympiad ${year}</h1>
                            <p class="plo-description">${data.description}</p>
                            ${metaHtml}<p>Check the other tabs in this year to know more!</p>
                        </ul>${cardsHtml}`;
}

function renderPLOSections() {
    for (const [year, data] of Object.entries(PLO_DATA)) {
        const el = document.getElementById(`pills-${year}-PLO`);
        if (!el) continue;
        el.innerHTML = renderPLOSection(year, data);
    }
}

document.addEventListener("DOMContentLoaded", renderPLOSections);
